from __future__ import annotations

from typing import Any


def render_issue_markdown(issue: dict[str, Any]) -> str:
    lines = [
        f"# {issue.get('title') or 'Offer issue'}",
        "",
        f"**Issue date:** {issue.get('issue_date')}  ",
        f"**Scope:** {issue.get('scope')}  ",
        f"**Status:** {issue.get('status')}  ",
        f"**Reviewer:** {issue.get('reviewer') or 'not signed'}",
        "",
        str(issue.get("standfirst") or ""),
        "",
        "| Date | Jurisdiction | Change | Action | Source |",
        "|---|---|---|---|---|",
    ]
    items: list[dict[str, Any]] = issue.get("items") or []
    for row in items:
        source = f"[{row.get('source_name', 'source')}]({row.get('source_url', '')})"
        lines.append(
            "| {date} | {jurisdiction} | {change} | {action} | {source} |".format(
                date=row.get("date", ""),
                jurisdiction=row.get("jurisdiction", ""),
                change=str(row.get("change") or row.get("headline") or "").replace("|", "\\|"),
                action=str(row.get("action") or "").replace("|", "\\|"),
                source=source,
            )
        )
    sources: list[dict[str, Any]] = issue.get("sources") or []
    if sources:
        lines.extend(["", "## Sources", ""])
        for src in sources:
            lines.append(f"- [{src.get('name', 'source')}]({src.get('url', '')})")
    lines.extend(
        [
            "",
            "## Provenance",
            "",
            "Generated by the System News offer pipeline from "
            f"`{issue.get('source_version') or 'unknown'}`.",
            "Draft only: no reviewer signature, no publish, no email.",
            "",
        ]
    )
    return "\n".join(lines)
